"""Write the presets as C headers for the firmware player.

    python scripts/export_c.py                    # every presets/*.json -> firmware/presets/<name>.h + all_presets.h
    python scripts/export_c.py my_flip.json       # one table
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from backflip import Preset  # noqa: E402

OUT = ROOT / "firmware" / "presets"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tables", nargs="*", help="preset names or .json files (default: all of presets/)")
    a = ap.parse_args()
    files = [Path(t) if Path(t).exists() else ROOT / "presets" / f"{t}.json" for t in a.tables] or \
        sorted((ROOT / "presets").glob("*.json"))
    OUT.mkdir(parents=True, exist_ok=True)
    keys = []
    for f in files:
        p = Preset.load(f)
        key = f.stem
        sym = "BF_" + key.upper()
        (OUT / f"{key}.h").write_text(p.to_c(sym))
        keys.append((key, sym, p))
        print(f"{f.name} -> firmware/presets/{key}.h  ({p.n} frames, {p.duration_ms()} ms)")
    lines = ["/* every table, for host/play_table.c and tests - generated by scripts/export_c.py */",
             "#ifndef BF_ALL_PRESETS_H", "#define BF_ALL_PRESETS_H", '#include "backflip_player.h"']
    lines += [f'#include "presets/{k}.h"' for k, _, _ in keys]
    lines += ["", "typedef struct { const char *key; const bf_table_t *table; uint16_t stand[12]; } bf_preset_entry_t;",
              "/* stand = the calibrated stand pose (ticks) of the robot the table was recorded on */",
              f"static const bf_preset_entry_t bf_presets[{len(keys)}] = {{"]
    lines += [f'    {{ "{k}", &{s}, {{ {", ".join(map(str, p.stand_ticks))} }} }},' for k, s, p in keys]
    lines += ["};", f"#define BF_N_PRESETS {len(keys)}", "#endif", ""]
    if not a.tables:
        (OUT / "all_presets.h").write_text("\n".join(lines))
        print("firmware/presets/all_presets.h")


if __name__ == "__main__":
    main()
